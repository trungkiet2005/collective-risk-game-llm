"""Supplement: one model in seat 1 beside five scripted partners of one kind.

Run from the repository root:
    python paper/AAMAS/analysis/supp_scripted.py

Design: 4 partner kinds (always 0, always 2, always 4, copy the group) x 5 models x
p in {0.1, 0.3, 0.5, 0.7, 0.9} x 10 games = 1,000 games. Seat 1 is the model.

Reuses scripted.py (replay, brute force over all 3^10 own-move sequences, per-game frame,
two-way variance decomposition) by import. Never calls scripted.main() or
scripted.figure(), which rewrite the paper's own tables, macros and figure.

Writes ONLY
    paper/AAMAS/supplement/tables/s_scr_{best,totals,outcomes,variance,settled,grok,fair,free}.tex
    paper/AAMAS/supplement/tables/snum_scripted.tex
    paper/AAMAS/supplement/figures/sfig_scripted_rounds.pdf (+ .png)

Statistics: unit = game; payoffs are EXPECTED over the catastrophe lottery; intervals are
95% percentile bootstraps over games (cd.boot_ci, fixed offsets from 7000 up). Rounding
is half-up throughout.

Consistency gate: every printed value that the paper already quotes (tables/num_scripted.tex
and tables/tab_settled.tex) is compared string for string; any difference raises.
"""
