    for m in cd.MODELS:
        w = d[d["model"] == m]
        if len(w) != 200:
            raise AssertionError(f"{m}: {len(w)} games")
        s = [one_way(w, c) for c in ("r1", "profile", "p")]
        lines.append(f"{cd.show(m)} & " + " & ".join(rf"\multicolumn{{2}}{{c}}{{{pct(v)}}}" for v in s) + r" \\")
        if m == "Grok":
            gate.macro("ScrGrokFirstMoveShare", pct(s[0]))
            gate.macro("ScrGrokProfileShareFour", pct(s[1]))
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_tabular("s_scr_grok.tex", lines)
    others = d[d["model"] != "Grok"]
    if not (others["r1"] == 2).all():
        raise AssertionError("a model other than Grok 4.20 opened with 0 or 4")
