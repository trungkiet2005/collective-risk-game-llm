# ------------------------------------------------------------------ formatting
def rnd(x: float, digits: int = 1) -> str:
    """Half-up rounding; LaTeX minus; never prints -0."""
    q = Decimal(1).scaleb(-digits)
    v = Decimal(repr(round(float(x), 9))).quantize(q, rounding=ROUND_HALF_UP)
    if v == 0:
        v = abs(v)
    s = f"{v:.{digits}f}"
    return "$-$" + s[1:] if s.startswith("-") else s


def pct(x: float) -> str:
    return rnd(100.0 * x, 0)


def ci(lo: float, hi: float) -> str:
    return f"[{rnd(lo)}, {rnd(hi)}]"


def seq(moves) -> str:
    return r"\,".join(str(int(a)) for a in moves)


def ptxt(p: float) -> str:
    return f"{p:g}"


FORBIDDEN = re.compile(r"--|\u2013|\u2014|all0|all2|all4|\bcond\b|exp_|scripted:|Legacy")


def write_tabular(name: str, lines) -> None:
    body = "\n".join(lines)
    bad = FORBIDDEN.search(body)
    if bad:
        raise RuntimeError(f"{name}: forbidden text {bad.group(0)!r}")
    if not (body.lstrip().startswith(r"\begin{tabular}") and body.rstrip().endswith(r"\end{tabular}")):
        raise RuntimeError(f"{name}: must contain exactly one tabular and nothing else")
    rows = sum(1 for ln in lines if ln.rstrip().endswith(r"\\"))
    if rows > MAX_ROWS:
        raise RuntimeError(f"{name}: {rows} rows > {MAX_ROWS}")
    OUT_T.mkdir(parents=True, exist_ok=True)
    (OUT_T / name).write_text(HEADER + "\n" + body + "\n", encoding="utf-8")
    print(f"wrote {OUT_T / name} ({rows} rows)")


def block(label: str, ncols: int) -> str:
    return rf"\multicolumn{{{ncols}}}{{@{{}}l}}{{\textit{{{label}}}}} \\"


def modes(items):
    """All values tied for the highest count, sorted, with that count."""
    c = Counter(items)
    top = max(c.values())
    return sorted(k for k, v in c.items() if v == top), top


# ------------------------------------------------------------------ gate
class Gate:
    """Values printed here that the paper already quotes. Compared string for string."""

    def __init__(self):
        self.macros: dict = {}
        self.settled: dict = {}

    def macro(self, name: str, value: str) -> None:
        if name in self.macros and self.macros[name] != value:
            raise RuntimeError(f"gate: {name} set twice ({self.macros[name]} vs {value})")
        self.macros[name] = value

    def check(self) -> None:
        text = (cd.TABLES / "num_scripted.tex").read_text(encoding="utf-8")
        paper = dict(re.findall(r"^\\newcommand\{\\(\w+)\}\{(.*)\}\s*$", text, re.M))
        problems = []
        for k, v in self.macros.items():
            if k not in paper:
                problems.append(f"{k} not in num_scripted.tex")
            elif paper[k] != v:
                problems.append(f"{k}: paper {paper[k]!r}, supplement {v!r}")
        tab = (cd.TABLES / "tab_settled.tex").read_text(encoding="utf-8")
        seen = 0
        for m in cd.MODELS:
            row = re.search(rf"^{re.escape(cd.show(m))} & (.*?) \\\\\s*$", tab, re.M)
            if not row:
                problems.append(f"tab_settled.tex: no row for {cd.show(m)}")
                continue
            vals = [v.strip() for v in row.group(1).split("&")]
            mine = [self.settled[(m, k, w)] for k in ("all0", "all4") for w in ("before", "after")]
            seen += 1
            if vals != mine:
                problems.append(f"tab_settled {cd.show(m)}: paper {vals}, supplement {mine}")
        if problems:
            raise RuntimeError("consistency gate failed:\n  " + "\n  ".join(problems))
        print(f"consistency gate passed: {len(self.macros)} macros of num_scripted.tex and "
              f"{seen} rows of tab_settled.tex match")


