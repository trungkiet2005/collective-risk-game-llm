def t_best(reach, gate: Gate) -> dict:
    sc.verify_best_response(reach)
    best = {k: {p: sc.best_totals(reach[k], p) for p in RISKS} for k in KINDS}
    n = 6
    lines = [r"\begin{tabular}{@{}lccccc@{}}", r"\toprule",
             r" & \multicolumn{5}{c}{Risk $p$} \\", r"\cmidrule(l){2-6}",
             "Partners & " + " & ".join(ptxt(p) for p in RISKS) + r" \\", r"\midrule",
             block("Best-response total over ten rounds", n)]
    for k in KINDS:
        lines.append(f"{KIND_NAME[k]} & " + " & ".join(
            " or ".join(str(t) for t in best[k][p][0]) for p in RISKS) + r" \\")
    lines += [r"\midrule", block("Best expected payoff", n)]
    for k in KINDS:
        lines.append(f"{KIND_NAME[k]} & " + " & ".join(rnd(best[k][p][1]) for p in RISKS) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_tabular("s_scr_best.tex", lines)
    return best


def best_text(totals) -> str:
    return " or ".join(str(int(t)) for t in totals)


def t_totals(d: pd.DataFrame, best, gate: Gate) -> float:
    n = 8
    lines = [r"\begin{tabular}{@{}lrrrrrrr@{}}", r"\toprule",
             r" & \multicolumn{5}{c}{Risk $p$} & All & $p>0.5$ minus \\",
             r"\cmidrule(lr){2-6}",
             "Model & " + " & ".join(ptxt(p) for p in RISKS) + r" & risks & $p<0.5$ \\",
             r"\midrule"]
    fair_change = []
    for i, k in enumerate(KINDS):
        if i:
            lines.append(r"\midrule")
        lines.append(block(KIND_NAME[k], n))
        for m in cd.MODELS:
            w = d[(d.profile == k) & (d.model == m)]
            by = w.groupby("p")["total"].mean()
            if len(w) != 50 or list(by.index) != list(RISKS):
                raise AssertionError(f"{k} {m}: {len(w)} games")
            change = w[w.p > 0.5]["total"].mean() - w[w.p < 0.5]["total"].mean()
            if k in ("all2", "cond"):
                fair_change.append(abs(change))
            cells = [rnd(by[p]) for p in RISKS] + [rnd(w["total"].mean()), rnd(change)]
            lines.append(f"{cd.show(m)} & " + " & ".join(cells) + r" \\")
            if m == "Qwen" and k == "all0":
                gate.macro("ScrQwenDefectPay", cells[5])
            if m == "Qwen" and k == "all2":
                gate.macro("ScrQwenFairPay", cells[5])
        # best-response row: every combination of tied totals across risks
        opts = [best[k][p][0] for p in RISKS]
        combos = sorted({float(np.mean(c)) for c in _product(opts)})
        lo = [best[k][p][0] for p in RISKS if p < 0.5]
        hi = [best[k][p][0] for p in RISKS if p > 0.5]
        if any(len(o) != 1 for o in lo + hi):
            raise AssertionError("best response tied away from p = 0.5")
        br_change = np.mean([o[0] for o in hi]) - np.mean([o[0] for o in lo])
        cells = [best_text(o) for o in opts] + [" or ".join(f"{c:g}" for c in combos),
                                                f"{br_change:g}"]
        lines.append("Best response & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_tabular("s_scr_totals.tex", lines)
    return max(fair_change)


def _product(opts):
    return itertools.product(*opts)


def t_outcomes(d: pd.DataFrame, best, gate: Gate) -> None:
    n = 6
    lines = [r"\begin{tabular}{@{}lrrrlr@{}}", r"\toprule",
             r" & Reached & Expected & \multicolumn{2}{c}{Gap to best response} & Exactly optimal \\",
             r"\cmidrule(lr){4-5}",
             r"Model & (of 50) & payoff & Mean & 95\% CI & (of 50) \\", r"\midrule"]
    n_opt = 0
    opt_totals = set()
    for i, k in enumerate(KINDS):
        if i:
            lines.append(r"\midrule")
        lines.append(block(KIND_NAME[k], n))
        for j, m in enumerate(cd.MODELS):
            w = d[(d.profile == k) & (d.model == m)]
            lo, hi = cd.boot_ci(w["gap"], offset=OFF_OUTCOMES + 10 * i + j)
            opt = w[w["gap"].abs() < 1e-9]
            n_opt += len(opt)
            opt_totals.update(opt["total"].tolist())
            reached = int(w["reached"].sum())
            lines.append(f"{cd.show(m)} & {reached} & {rnd(w['exp_pay'].mean())} & "
                         f"{rnd(w['gap'].mean())} & {ci(lo, hi)} & {len(opt)}" + r" \\")
            if k == "all2" and m == "Flash-Lite":
                gate.macro("ScrFlashFairReach", str(reached))
            if k == "all2" and m == "Qwen":
                gate.macro("ScrQwenFairMiss", str(50 - reached))
        # best responder: payoff is unique; reaching the target is not at a tie
        pay = np.mean([best[k][p][1] for p in RISKS])
        reach_counts = sorted({sum(10 * int(t > 0 or k == "all4") for t in c)
                               for c in _product([best[k][p][0] for p in RISKS])})
        lines.append(f"Best response & {' or '.join(map(str, reach_counts))} & {rnd(pay)} & "
                     f"{rnd(0)} &  & 50" + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    gate.macro("ScrOptimalGames", str(n_opt))
    if opt_totals != {20}:
        raise AssertionError(f"exactly optimal games with totals {sorted(opt_totals)}")
    gate.macro("ScrOptimalAllTwenty", "every")
    write_tabular("s_scr_outcomes.tex", lines)


def t_variance(d: pd.DataFrame, gate: Gate) -> None:
    three = d[d["profile"].isin(["all0", "all2", "all4"])]
    shares = {m: sc.two_way_shares(three[three["model"] == m]) for m in cd.MODELS}
    ref = three[three["model"] == "Luna"][["profile", "p"]].copy()
    ref["total"] = [20 if (pr == "all2" and p >= 0.5) else 0 for pr, p in zip(ref.profile, ref.p)]
    shares_ref = sc.two_way_shares(ref)
    lines = [r"\begin{tabular}{@{}lrrrrr@{}}", r"\toprule",
             r" & \multicolumn{5}{c}{Share of the variation in the total (\%)} \\",
             r"\cmidrule(l){2-6}",
             r" & Partner & & Partner kind & Risk and & \\",
             r"Model & kind & Risk & $\times$ risk & interaction & Residual \\", r"\midrule"]

    def row(label, s):
        return (f"{label} & {pct(s['profile'])} & {pct(s['risk'])} & {pct(s['inter'])} & "
                f"{pct(s['risk'] + s['inter'])} & {pct(s['resid'])}" + r" \\")

    for m in cd.MODELS:
        lines.append(row(cd.show(m), shares[m]))
    lines += [r"\midrule", row("Best response", shares_ref), r"\bottomrule", r"\end{tabular}"]
    write_tabular("s_scr_variance.tex", lines)
    four = ["Haiku", "Flash-Lite", "Luna", "Qwen"]
    prof = {m: pct(shares[m]["profile"]) for m in four}
    risk = {m: pct(shares[m]["risk"] + shares[m]["inter"]) for m in four}
    gate.macro("ScrOpponentShareMin", min(prof.values(), key=int))
    gate.macro("ScrOpponentShareMax", max(prof.values(), key=int))
    gate.macro("ScrRiskShareMax", max(risk.values(), key=int))
    gate.macro("ScrGrokOpponentShare", pct(shares["Grok"]["profile"]))
    gate.macro("ScrGrokRiskShare", pct(shares["Grok"]["risk"] + shares["Grok"]["inter"]))
    gate.macro("ScrGrokResidShare", pct(shares["Grok"]["resid"]))
    gate.macro("ScrBestResponderRiskShare", pct(shares_ref["risk"] + shares_ref["inter"]))


def t_settled(d: pd.DataFrame, gate: Gate) -> None:
    dom = d[d["profile"].isin(["all0", "all4"])]
    gate.macro("ScrDominatedGames", str(len(dom)))
    gate.macro("ScrBestResponseDominated", str(int((dom["total"] == 0).sum())))
    gate.macro("ScrMinTotalDominated", str(int(dom["total"].min())))
    rounds = sorted(int(s) for s in dom["settled"].unique())
    n = 9
    lines = [r"\begin{tabular}{@{}lrrlrrrlr@{}}", r"\toprule",
             r" & \multicolumn{4}{c}{Always 0} & \multicolumn{4}{c}{Always 4} \\",
             r"\cmidrule(lr){2-5}\cmidrule(l){6-9}",
             block("Games settled after each round, all five models (of 250)", n)]
    for t in rounds:
        c = [int((dom[dom.profile == k]["settled"] == t).sum()) for k in ("all0", "all4")]
        lines.append(f"Round {t} & " + " & ".join(rf"\multicolumn{{4}}{{c}}{{{v}}}" for v in c) + r" \\")
    lines += [r"\midrule",
              r" & \multicolumn{2}{c}{Units paid} & After: & No waste & "
              r"\multicolumn{2}{c}{Units paid} & After: & No waste \\",
              r"Model & Before & After & 95\% CI & (of 50) & Before & After & 95\% CI & (of 50) \\",
              r"\midrule"]
    for j, m in enumerate(cd.MODELS):
        cells = []
        clean = 0
        pooled = []
        for i, k in enumerate(("all0", "all4")):
            w = dom[(dom["model"] == m) & (dom["profile"] == k)]
            if len(w) != 50:
                raise AssertionError(f"{m} {k}: {len(w)} games")
            before = float(np.mean([int(x[: int(s)].sum()) for x, s in zip(w["x"], w["settled"])]))
            after = float(w["waste"].mean())
            lo, hi = cd.boot_ci(w["waste"], offset=OFF_SETTLED + 10 * i + j)
            zero = int((w["waste"] == 0).sum())
            clean += zero
            pooled += w["waste"].tolist()
            gate.settled[(m, k, "before")] = rnd(before)
            gate.settled[(m, k, "after")] = rnd(after)
            cells += [rnd(before), rnd(after), ci(lo, hi), str(zero)]
        lines.append(f"{cd.show(m)} & " + " & ".join(cells) + r" \\")
        gate.macro(f"ScrWaste{cd.MACRO[m]}", rnd(np.mean(pooled)))
        if m in ("Luna", "Qwen", "Grok"):
            gate.macro(f"ScrClean{cd.MACRO[m]}", pct(clean / len(pooled)))
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_tabular("s_scr_settled.tex", lines)


def one_way(df: pd.DataFrame, col: str, y: str = "total") -> float:
    gm = df[y].mean()
    sst = ((df[y] - gm) ** 2).sum()
    return float(((df.groupby(col)[y].transform("mean") - gm) ** 2).sum() / sst)


