# ------------------------------------------------------------------ formatting
def rnd(x: float, digits: int = 0) -> str:
    q = Decimal(1).scaleb(-digits)
    v = Decimal(repr(round(float(x), 9))).quantize(q, rounding=ROUND_HALF_UP)
    if v == 0:
        v = abs(v)
    s = f"{v:.{digits}f}"
    return "$-$" + s[1:] if s.startswith("-") else s


def pct(x: float) -> str:
    return rnd(100.0 * x, 0)


def pci(est, lo, hi) -> str:
    return f"{pct(est)} [{pct(lo)}, {pct(hi)}]"


def dci(est, lo, hi, digits=2) -> str:
    return f"{rnd(est, digits)} [{rnd(lo, digits)}, {rnd(hi, digits)}]"


FORBIDDEN = re.compile("|".join(["--", chr(0x2013), chr(0x2014), "exp_", "scripted:", "Legacy"]))


def write_tabular(name: str, lines) -> None:
    body = "\n".join(lines)
    bad = FORBIDDEN.search(body)
    if bad:
        raise RuntimeError(f"{name}: forbidden text {bad.group(0)!r}")
    if not (body.startswith(r"\begin{tabular}") and body.endswith(r"\end{tabular}")):
        raise RuntimeError(f"{name}: must contain exactly one tabular and nothing else")
    OUT_T.mkdir(parents=True, exist_ok=True)
    (OUT_T / name).write_text(HEADER + "\n" + body + "\n", encoding="utf-8")
    print(f"wrote {(OUT_T / name).relative_to(cd.REPO)}")


def note(text: str, ncols: int, width: float) -> str:
    """Note row set just below the table's natural width in the supplement's fonts, so it never stretches a column."""
    return rf"\multicolumn{{{ncols}}}{{@{{}}p{{{width}\linewidth}}@{{}}}}{{\footnotesize {text}}} \\"


def guard(label: str, value_pct: float, expected: float, tol: float = TOL) -> None:
    if abs(value_pct - expected) > tol:
        raise RuntimeError(f"{label}: {value_pct:.1f} drifted from {expected} by more than {tol} points; "
                           f"revisit the text")


# ------------------------------------------------------------------ bootstrap
def ratio_boot(event, gid, offset):
    """Pooled share of decisions with a game-level percentile bootstrap."""
    s = pd.DataFrame({"e": np.asarray(event, float), "g": np.asarray(gid)}).groupby("g").e.agg(["sum", "count"])
    num, den = s["sum"].to_numpy(float), s["count"].to_numpy(float)
    if len(num) == 0:
        raise ValueError("empty sample")
    idx = np.random.default_rng(cd.SEED + offset).integers(0, len(num), (N_BOOT, len(num)))
    draws = num[idx].sum(1) / den[idx].sum(1)
    return (num.sum() / den.sum(), float(np.percentile(draws, 2.5)), float(np.percentile(draws, 97.5)),
            len(num), int(den.sum()))


def mean_boot(values, offset):
    v = np.asarray(values, float)
    idx = np.random.default_rng(cd.SEED + offset).integers(0, len(v), (N_BOOT, len(v)))
    draws = v[idx].mean(1)
    return v.mean(), float(np.percentile(draws, 2.5)), float(np.percentile(draws, 97.5)), len(v)


# ------------------------------------------------------------------ decisions
def nearest(v: float) -> int:
    """Engine rule: nearest legal option, ties keep the lower one."""
    best, bd = OPTIONS[0], abs(v - OPTIONS[0])
    for o in OPTIONS[1:]:
        if abs(v - o) < bd:
            best, bd = o, abs(v - o)
    return best


def decisions(games: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for g in games.itertuples():
        S = g.strat.astype(int)
        names = [cd.SLUG.get(s) for s in g.llm]
        pot_start = np.r_[0.0, np.cumsum(S.sum(axis=0))[:-1]]
        for i, m in enumerate(names):
            if m is None:
                continue
            others = [j for j in range(cd.N_PLAYERS) if j != i]
            for t in range(cd.N_ROUNDS):
                need = cd.TARGET - pot_start[t]
                rl = cd.N_ROUNDS - t
                rows.append((g.gid, g.exp, round(g.p, 3), m, t + 1, int(S[i, t]),
                             int(S[i, t - 1]) if t else -1,
                             float(S[others, t - 1].mean()) if t else np.nan,
                             float(pot_start[t] - 12 * t), float(need), rl,
                             int(need <= 0), int(need > 24 * rl), float(need / (6 * rl)), int(g.reached)))
    return pd.DataFrame(rows, columns=["gid", "exp", "p", "model", "t", "a", "own_prev", "oth_prev", "pace",
                                       "need", "rl", "reached", "unreach", "req", "final_reached"])


