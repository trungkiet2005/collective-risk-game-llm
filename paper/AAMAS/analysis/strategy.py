              "Change without $p$ (pp) & " + " & ".join(dci(*(100 * np.array(res[m]["dp"][:3])), digits=1)
                                                       for m in cd.MODELS) + r" \\",
              "Tree minus best rule (pp) & " + " & ".join(dci(*(100 * np.array(res[m]["gain"][:3])), digits=1)
                                                         for m in cd.MODELS) + r" \\",
              r"\midrule",
              "Games & " + " & ".join(str(res[m]["n_games"]) for m in cd.MODELS) + r" \\",
              "Decisions & " + " & ".join(f"{res[m]['n_dec']:,}".replace(",", "{,}") for m in cd.MODELS) + r" \\",
