def fe_coef(y, x, own, cell):
    ok = np.isfinite(y)
    y, x, own, cell = y[ok], x[ok], own[ok], cell[ok]
    _, c = np.unique(cell, return_inverse=True)
    cnt = np.bincount(c)

    def dm(v):
        return v - (np.bincount(c, weights=v) / cnt)[c]
    A = np.column_stack([dm(x), dm(own)])
    if np.allclose(A[:, 1], 0) or np.linalg.matrix_rank(A) < 2:
        A = A[:, :1]
    return float(np.linalg.lstsq(A, dm(y), rcond=None)[0][0])


