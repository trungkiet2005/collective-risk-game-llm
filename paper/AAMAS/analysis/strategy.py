    lines = [r"\begin{tabular}{@{}l" + "c" * len(cd.MODELS) + "@{}}", r"\toprule",
             " & " + head1 + r" \\", r"Accuracy (\%) & " + head2 + r" \\", r"\midrule",
             rf"\multicolumn{{{ncols}}}{{@{{}}l}}{{\textit{{Named rules (best per model in bold)}}}} \\"]
    for k, lab in RULES:
        cells = []
        for m in cd.MODELS:
            c = pci(*res[m][k][:3])
            cells.append(rf"\textbf{{{c}}}" if res[m]["best"] == k else c)
