"""Strategies behind the numbers: last round, simple rules, the Grok opening, equilibrium benchmark.

Run from the repository root:
    python paper/AAMAS/analysis/strategy.py

Reads results/ through crsd_data (read-only; never Legacy_Results/, never writes under results/).

Base-prompt corpus = exp_baseline, exp_evprobe, exp_mixed and the four scripted-partner
designs exp_bestresponse_{defect,coop,carry,cond}. One decision = one model seat in one round.

Writes ONLY
    paper/AAMAS/tables/num_strategy.tex
    paper/AAMAS/supplement/tables/s_strat_{endgame,rules,opening,equilibrium}.tex

STATISTICS. Unit of resampling = game. Every interval is a 95% percentile bootstrap with
2,000 resamples over games and a fixed seed (cd.SEED + a fixed offset per quantity). A share
of decisions is the pooled ratio (decisions in the state that satisfy the event over all
decisions in the state); its bootstrap resamples games and recomputes the pooled ratio.
The opening regression resamples games within design cells. Rounding is half-up.

A. LAST ROUND. need = 120 minus the pool at the start of round 10 (what the seats saw).
   Reached: need <= 0. Slack: 0 < need <= 10 (the other five paying 2 already reach 120).
   Pivotal: need == 12 (the seat's own 2 is needed). Late safe: rounds 7 to 9 whose starting
   pool is already >= 120. Luna self-play (exp_baseline + exp_evprobe): target rate of games
   whose pool after round 9 lies strictly between 108 and 120 (ahead of the fair pace)
   versus exactly 108 (on pace).
B. RULES. Exact-match accuracy of named rules; majority class; depth-5 decision tree
   (min 50 decisions per leaf) with game-grouped 5-fold CV, and the same tree without risk p.
C. GROK OPENING. exp_mixed games holding Grok and one other model. Grok's round-1 move is made
   before any history, and varies across repetitions of the same cell. Within cells
   (partner model x number of Grok seats x p), OLS of the partner's outcome on the mean
   Grok opening move, with cell fixed effects and the partner's own mean opening move as a
   control (dropped when it does not vary within cells). Outcomes: the partner's per-seat
   total over rounds 2 to 10; its mean payment per seat-round over rounds 2 to 10 whose
   starting pool is below 120 (before), and at or above 120 (after; games without such
   rounds drop out).
D. EQUILIBRIUM. Proposition 1 (p < 1): the Nash equilibria are x = 0, and X = T with
   x_i <= 40p. The first gives (1-p)40 per seat; the second exists only for p >= 0.5 and
   gives 20 per seat, which is >= (1-p)40 there. So the worst equilibrium welfare per seat
   is (1-p)40 at every p < 1. Share of exp_baseline self-play games whose expected welfare
   per seat is strictly below it, for 0.5 < p < 1 and for p < 0.5. p = 1 is excluded
   (welfare cannot fall below 0) and so is p = 0.5 (the two sets of equilibria tie).
"""
