def rule_predictions(d):
    t1 = (d.t == 1).to_numpy()
    settled = ((d.reached == 1) | (d.unreach == 1)).to_numpy()
    tracker = np.clip(np.ceil(d.req.to_numpy() / 2) * 2, 0, 4)
    return {
        "always2": np.full(len(d), 2),
        "repeat": np.where(t1, 2, d.own_prev.to_numpy()),
        "copy": np.where(t1, 2, d.oth_prev.fillna(2.0).map(nearest).to_numpy()),
        "skipper": np.where(d.t.to_numpy() == 10, 0, 2),
        "settled": np.where(settled, 0, 2),
        "tracker": np.where(settled, 0, tracker).astype(int),
        "riskneutral": np.where(d.p.to_numpy() >= 0.5, np.where(d.reached.to_numpy() == 1, 0, 2), 0),
    }


def featurize(d):
    X = pd.DataFrame({
        "own0": (d.own_prev == 0).astype(int), "own2": (d.own_prev == 2).astype(int),
        "own4": (d.own_prev == 4).astype(int), "first": (d.t == 1).astype(int),
        "oth_prev": d.oth_prev.fillna(2.0), "pace12": d.pace / 12.0, "rl": d.rl,
        "last": (d.t == 10).astype(int), "reached": d.reached, "unreach": d.unreach, "p": d.p,
        "req": d.req.clip(-2, 6)})
    return X[FEATS].to_numpy(float)


def cv_correct(X, y, groups):
    pred = np.zeros(len(y), int)
    for tr, te in GroupKFold(n_splits=5).split(X, y, groups):
        clf = DecisionTreeClassifier(max_depth=5, min_samples_leaf=50, random_state=0)
        pred[te] = clf.fit(X[tr], y[tr]).predict(X[te])
    return pred == y


def rules(D):
    d0 = D[D.exp.isin(BASE)]
    res = {}
    print("\n[B] exact-match accuracy over the base-prompt corpus (pooled decisions, game bootstrap)")
    for mi, m in enumerate(cd.MODELS):
        d = d0[d0.model == m].reset_index(drop=True)
        y, gid = d.a.to_numpy(), d.gid.to_numpy()
        r = {}
        for ri, (k, pr) in enumerate(rule_predictions(d).items()):
            r[k] = ratio_boot(pr == y, gid, 1000 + 100 * mi + ri)
        maj = int(pd.Series(y).mode()[0])
        r["majority"] = ratio_boot(y == maj, gid, 1000 + 100 * mi + 20)
        X = featurize(d)
        full = cv_correct(X, y, gid)
        nop = cv_correct(np.delete(X, FEATS.index("p"), axis=1), y, gid)
        r["tree"] = ratio_boot(full, gid, 1000 + 100 * mi + 21)
        r["treenop"] = ratio_boot(nop, gid, 1000 + 100 * mi + 22)
        best = max((k for k, _ in RULES), key=lambda k: r[k][0])
        r["dp"] = ratio_boot(nop.astype(float) - full.astype(float), gid, 1000 + 100 * mi + 23)
        best_correct = rule_predictions(d)[best] == y
        r["gain"] = ratio_boot(full.astype(float) - best_correct.astype(float), gid, 1000 + 100 * mi + 24)
        r["best"], r["maj_class"], r["n_games"], r["n_dec"] = best, maj, r["tree"][3], len(y)
        res[m] = r
        print(f"  {m:10} games={r['n_games']} decisions={len(y)} majority class={maj} best rule={best}")
        print("     " + "  ".join(f"{k}={100 * r[k][0]:.1f}[{100 * r[k][1]:.1f},{100 * r[k][2]:.1f}]"
                                  for k in [k for k, _ in RULES] + ["majority", "tree", "treenop"]))
