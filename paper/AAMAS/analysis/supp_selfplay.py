_SHORT = re.compile(r"(?<![\w.-])(Haiku|Luna|Flash-Lite|Qwen|Grok)(?![\w.-])")


def audit_text(name: str, text: str, body: list) -> None:
    for bad in ("--", "\u2013", "\u2014"):
        if bad in text:
            raise RuntimeError(f"{name}: forbidden dash {bad!r}")
    if re.search(r"exp_|\.csv|\bE\d\b|mix__|evprobe|nohint|para\d|temp0", text):
        raise RuntimeError(f"{name}: internal name in reader-facing text")
    rows = [ln for ln in body if ln.rstrip().endswith("\\\\")]
    if len(rows) > MAX_ROWS:
        raise RuntimeError(f"{name}: {len(rows)} rows, limit {MAX_ROWS}")
    stripped = "\n".join(body)
    for full in cd.DISPLAY.values():
        stripped = stripped.replace(full, "")
    hit = _SHORT.search(stripped)
    if hit:
        raise RuntimeError(f"{name}: bare model name {hit.group(0)!r} in a table row")


def emit(name: str, colspec: str, head: list, body: list) -> pathlib.Path:
    lines = [HEADER, f"\\begin{{tabular}}{{{colspec}}}", r"\toprule", *head, r"\midrule",
             *body, r"\bottomrule", r"\end{tabular}"]
    text = "\n".join(lines) + "\n"
    audit_text(name, text, body)
    OUT_T.mkdir(parents=True, exist_ok=True)
    path = OUT_T / name
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(cd.REPO)} ({sum(ln.endswith(chr(92) * 2) for ln in body)} body rows)")
    return path


# ------------------------------------------------------------------ consistency gate
class Gate:
    """Everything the supplement prints that the paper also prints must agree exactly."""

    def __init__(self):
        text = (cd.TABLES / "num_selfplay.tex").read_text(encoding="utf-8")
        self.macros = dict(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}\s*$", text, flags=re.M))
        self.models = self._rows("tab_models.tex")
        self.robust = self._rows("tab_robust.tex")
        self.n = 0

    @staticmethod
    def _rows(filename):
        lines = (cd.TABLES / filename).read_text(encoding="utf-8").splitlines()
        start = lines.index(r"\midrule")
        stop = lines.index(r"\bottomrule")
        out = {}
        for ln in lines[start + 1:stop]:
            cells = [c.strip() for c in ln.rstrip().removesuffix("\\\\").split(" & ")]
            out[cells[0]] = cells[1:]
        return out

    def check(self, what: str, mine: str, paper: str) -> None:
        self.n += 1
        if str(mine) != str(paper):
            raise RuntimeError(f"supplement disagrees with the paper on {what}: "
                               f"supplement prints {mine!r}, paper prints {paper!r}")

    def macro(self, name: str, mine) -> None:
        if name not in self.macros:
            raise RuntimeError(f"macro \\{name} not found in num_selfplay.tex")
        self.check(f"\\{name}", str(mine), self.macros[name])

    def model_cell(self, m: str, col: int, mine: str, what: str) -> None:
        self.check(f"tab_models {cd.show(m)} {what}", mine, self.models[cd.show(m)][col])

    def robust_cell(self, row: str, m: str, mine: str, bold: bool) -> None:
        cell = self.robust[row][MODELS.index(m)]
        paper_bold = cell.startswith(r"\textbf{")
        value = cell[len(r"\textbf{"):-1] if paper_bold else cell
        self.check(f"tab_robust {row} / {cd.show(m)}", mine, value)
        self.check(f"tab_robust bold {row} / {cd.show(m)}", str(bold), str(paper_bold))


