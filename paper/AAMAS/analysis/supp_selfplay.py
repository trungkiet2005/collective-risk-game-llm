class SupMacros(cd.Macros):
    def write_supp(self) -> pathlib.Path:
        OUT_T.mkdir(parents=True, exist_ok=True)
        path = OUT_T / "snum_selfplay.tex"
        existing = set()
        for f in cd.TABLES.glob("num_*.tex"):
            existing |= set(re.findall(r"\\newcommand\{\\([A-Za-z]+)\}", f.read_text(encoding="utf-8")))
        clash = [k for k in self.items if k in existing or not k.startswith("Sup")]
        if clash:
            raise RuntimeError(f"supplement macro names clash with the paper or lack the Sup prefix: {clash}")
        lines = [HEADER] + [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in self.items.items()]
        text = "\n".join(lines) + "\n"
        if "--" in text or "\u2013" in text or "\u2014" in text:
            raise RuntimeError("snum_selfplay.tex: forbidden dash")
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(cd.REPO)} ({len(self.items)} macros)")
        return path


