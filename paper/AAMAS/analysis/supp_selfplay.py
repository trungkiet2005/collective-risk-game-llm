            S.add("SupNoHintHaikuExact", vals["Haiku"][1])
            G.macro("NoCueFlashExactPct", vals["Flash-Lite"][1])
            G.macro("NoCueLunaExactBasePct", vals["Luna"][0])
            G.macro("NoCueLunaExactPct", vals["Luna"][1])
