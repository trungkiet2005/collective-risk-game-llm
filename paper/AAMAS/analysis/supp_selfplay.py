def t_design_counts(games, units, seats, G, S):
    rows = [("Self-play grid", BASE), ("Rerun (in-game questions)", "exp_evprobe"),
            ("No hint", "exp_nohint"), ("Rewording 1", "exp_para1"), ("Rewording 2", "exp_para2"),
            ("Temperature zero", "exp_baseline_temp0"), ("Neutral wording", "exp_wording"),
            ("Goal stated", "exp_neutral")]
    scripted = [("Partners always pay 0", "exp_bestresponse_defect"),
                ("Partners always pay 2", "exp_bestresponse_coop"),
                ("Partners always pay 4", "exp_bestresponse_carry"),
                ("Partners copy the group", "exp_bestresponse_cond")]
    mixed = ("Two models at one table", "exp_mixed")

    tot = dict(games=0, dec=0, parse=0)
    counts = {}

    def line(label, e):
        g = games[games.exp == e]
        per_model = units[units.exp == e].groupby("model").size()
        if per_model.nunique() != 1 or len(per_model) != len(MODELS):
            raise RuntimeError(f"{label}: models do not play the same number of games")
        n_dec = int((seats.exp == e).sum()) * cd.N_ROUNDS
        n_parse = int(g.n_parse.sum())
        tot["games"] += len(g)
        tot["dec"] += n_dec
        tot["parse"] += n_parse
        counts[e] = len(g)
        return (f"{label} & {risk_list(g.p.unique())} & {thousands(per_model.iloc[0])} & "
                f"{thousands(len(g))} & {thousands(n_dec)} & {n_parse} \\\\")

    body = [line(label, e) for label, e in rows]
    body.append(r"One model, five scripted partners & & & & & \\")
    body += [line(r"\quad " + label, e) for label, e in scripted]
    body.append(line(*mixed))
    body += [r"\midrule",
             f"Total & & & {thousands(tot['games'])} & {thousands(tot['dec'])} & {tot['parse']} \\\\"]
    head = [r" & & Games per & Total & Model & Without the \\",
            r"Design & Risk levels $p$ & model & games & decisions & marker \\"]
    emit("s_design_counts.tex", "@{}llrrrr@{}", head, body)

    G.macro("CntGames", thousands(tot["games"]))
    G.macro("CntDecisions", thousands(tot["dec"]))
    G.macro("CntParseFail", str(tot["parse"]))
    G.macro("CntGamesBaseline", thousands(counts[BASE]))
    G.macro("CntGamesProbe", thousands(counts["exp_evprobe"]))
    G.macro("CntGamesNoCue", thousands(counts["exp_nohint"]))
    G.macro("CntGamesPara", thousands(counts["exp_para1"] + counts["exp_para2"]))
    G.macro("CntGamesTempZero", thousands(counts["exp_baseline_temp0"]))
    G.macro("CntGamesWording", thousands(counts["exp_wording"]))
    G.macro("CntGamesNeutral", thousands(counts["exp_neutral"]))
    G.macro("CntGamesScripted", thousands(sum(counts[e] for _, e in scripted)))
    G.macro("CntGamesMixed", thousands(counts["exp_mixed"]))
    if len(games) != tot["games"]:
        raise RuntimeError("design rows do not cover every game")
    print(f"  designs: {tot['games']} games, {tot['dec']} decisions, {tot['parse']} without the marker")


def t_lottery(games, G, S):
    draws = cd.lottery_draws()
    missed = games[games.reached == 0]
    pred = np.array([draws[r] < p for r, p in zip(missed.rep, missed.p)])
    if (pred != missed.catastrophe.astype(bool).values).any() or games[games.reached == 1].catastrophe.any():
        raise RuntimeError("catastrophe flags do not follow 'draw < p' on missed games")
    base = games[games.exp == BASE]
    body = []
    tm = tc = 0
    te = 0.0
    for rep, u in enumerate(draws):
        first = min(p for p in RISKS if p > u)
        b = base[(base.rep == rep) & (base.reached == 0)]
        n_m, n_c, n_e = len(b), int(b.catastrophe.sum()), float(b.p.sum())
        tm, tc, te = tm + n_m, tc + n_c, te + n_e
        body.append(f"{rep + 1} & {rnd(u, 3)} & $p \\ge {first:g}$ & {n_m} & {n_c} & {rnd(n_e, 1)} \\\\")
    body += [r"\midrule", f"All & & & {tm} & {tc} & {rnd(te, 1)} \\\\"]
    head = [r" & & A missed game & \multicolumn{3}{c}{Self-play grid} \\",
            r"\cmidrule(l){4-6}",
            r" & & ends in & Missed & \multicolumn{2}{c}{Catastrophes} \\",
            r"Repetition & Draw & catastrophe at & games & Realised & Expected \\"]
    emit("s_lottery.tex", "@{}rrlrrr@{}", head, body)
    G.macro("LotRealCat", str(tc))
    G.macro("LotExpCat", str(half_up_int(te)))
    if not max(draws) < float(G.macros["LotMaxDraw"]):
        raise RuntimeError("a lottery draw is not below \\LotMaxDraw")
    high = base[(base.reached == 0) & (base.p >= cd.PSTAR)]
    if int(high.catastrophe.sum()) != len(high):
        raise RuntimeError("a missed grid game at p >= 0.5 escaped the catastrophe")
    S.add("SupLotMissed", str(tm))
    S.add("SupLotMissedHigh", str(len(high)))
    S.add("SupLotCatLow", str(tc - len(high)))
    print(f"  lottery: grid misses {tm} ({len(high)} at p>=0.5), catastrophes {tc}, expected {te:.2f}")


def grid_head(extra: str = "All"):
    n = len(RISKS)
    tail = " & " if extra else ""
    return [f" & \\multicolumn{{{n}}}{{c}}{{Catastrophe probability $p$}}{tail} \\\\",
            f"\\cmidrule(lr){{2-{n + 1}}}",
            "Model & " + " & ".join(f"{p:g}" for p in RISKS) + (f" & {extra}" if extra else "") + r" \\"]


def cellwise(base_u, m, fn):
    d = base_u[base_u.model == m]
    out = []
    for p in RISKS:
        c = d[d.p == p]
        if len(c) != 10:
            raise RuntimeError(f"{m} at p={p}: {len(c)} games, expected 10")
        out.append(fn(c))
    return out


def t_grid(games, units, seats, G, S):
    base_u = units[units.exp == BASE].copy()
    base_s = seats[seats.exp == BASE].copy()
    base_u["opt"] = cd.opt_payoff(base_u.p)
    spec = "@{}l" + "r" * len(RISKS) + "@{\\hspace{10pt}}r@{}"

    # ---- mean seat total
    opt_row = ["0" if p < cd.PSTAR else ("0 or 20" if np.isclose(p, cd.PSTAR) else "20") for p in RISKS]
    body = [r"\emph{Optimum} & " + " & ".join(opt_row) + r" \\"]
    for m in MODELS:
        vals = cellwise(base_u, m, lambda c: c.own.mean())
        body.append(cd.show(m) + " & " + " & ".join(rnd(v, 1) for v in vals) + r" \\")
        G.macro("GridZero" + m.replace("-", ""), rnd(vals[0], 1))
    emit("s_grid_total.tex", "@{}l" + "r" * len(RISKS) + "@{}", grid_head(extra=""), body)

    # ---- target reached
    body = []
    for m in MODELS:
        vals = cellwise(base_u, m, lambda c: c.reached.mean())
        allv = pc(base_u[base_u.model == m].reached.mean())
        G.model_cell(m, 2, allv, "Target (%)")
        body.append(cd.show(m) + " & " + " & ".join(pc(v) for v in vals) + f" & {allv} \\\\")
    emit("s_grid_reach.tex", spec, grid_head(), body)

    # ---- exact split, share of seats
    body = []
    for m in MODELS:
        s = base_s[base_s.model == m]
        vals = [s[s.p == p].traj.map(lambda t: all_equal(t, 2)).mean() for p in RISKS]
        if any((s.p == p).sum() != 60 for p in RISKS):
            raise RuntimeError(f"{m}: a grid cell does not hold 60 seats")
        allv = pc(s.traj.map(lambda t: all_equal(t, 2)).mean())
        G.model_cell(m, 1, allv, "Exact split (%)")
        if m == "Flash-Lite":
            G.macro("GridFlashExactPct", allv)
        body.append(cd.show(m) + " & " + " & ".join(pc(v) for v in vals) + f" & {allv} \\\\")
    emit("s_grid_exact.tex", spec, grid_head(), body)

    # ---- share of opt(p) lost
    def lost(c):
        return 1.0 - c.exp_pay.mean() / c.opt.mean()

    body = []
    for m in MODELS:
        vals = cellwise(base_u, m, lost)
        allv = pc(lost(base_u[base_u.model == m]))
        G.model_cell(m, 4, allv, "Lost (%)")
        body.append(cd.show(m) + " & " + " & ".join(pc(v) for v in vals) + f" & {allv} \\\\")
    panel = [lost(base_u[base_u.p == p]) for p in RISKS]
    panel_all = pc(lost(base_u))
    G.macro("GridLossPanelPct", panel_all)
    for m, key in (("Grok", "GridGrokLossPct"), ("Flash-Lite", "GridFlashLossPct"), ("Qwen", "GridQwenLossPct")):
        G.macro(key, pc(lost(base_u[base_u.model == m])))
    body += [r"\midrule", r"\emph{Panel} & " + " & ".join(pc(v) for v in panel) + f" & {panel_all} \\\\"]
    emit("s_grid_lost.tex", spec, grid_head(), body)


def t_grid_models(units, seats, G, S):
    sp._OFFSET[0] = 5000
    base_u = units[units.exp == BASE].copy()
    base_s = seats[seats.exp == BASE].copy()
    base_u["opt"] = cd.opt_payoff(base_u.p)
    base_u["loss"] = base_u.opt - base_u.exp_pay
    # Loss decomposition, exactly as in selfplay.main():
    reached = base_u.reached.values == 1
    below = base_u.p.values < cd.PSTAR
    A = np.where(reached, (base_u.G.values - cd.TARGET) / cd.N_PLAYERS, 0.0)
    B = np.where(below & reached, base_u.opt.values - cd.FAIR_TOTAL, 0.0) \
        + np.where(below & ~reached, base_u.loss.values, 0.0)
    C = np.where(~below & ~reached, base_u.loss.values, 0.0)
    if not np.allclose(A + B + C, base_u.loss.values):
        raise RuntimeError("loss decomposition does not add up")
    if (A < -1e-9).any() or (B < -1e-9).any() or (C < -1e-9).any():
        raise RuntimeError("negative loss component")
    base_u["A"], base_u["B"], base_u["C"] = A, B, C
    labels = {"A": "past 120", "B": "below $p^*$", "C": "missed"}

    def row(name, d, s, strata_zero, strata_lost, offset):
        d0 = d[d.p == 0]
        s0 = s[s.p == 0]
        own0 = d0.own.mean()
        lo0, hi0 = (cd.boot_ci(d0.own, offset=offset) if strata_zero is None
                    else sp.strat_boot_ci(d0.own, strata_zero))
        lost = 100.0 * (1.0 - d.exp_pay.mean() / d.opt.mean())
        lo, hi = sp.strat_boot_ci(d.exp_pay, strata_lost, stat="ratio", denom=d.opt)
        t = d.loss.sum()
        shares = {k: d[k].sum() / t for k in "ABC"}
        cells = [name, rnd(own0, 1), ci(lo0, hi0), f"{int((s0.own > 0).sum())}/{len(s0)}",
                 rnd(lost, 0), ci(lo, hi, 0), pc(shares["B"]), pc(shares["A"]), pc(shares["C"])]
        return cells, shares, (lo, hi)

    body = []
    for i, m in enumerate(MODELS):
        d = base_u[base_u.model == m]
        s = base_s[base_s.model == m]
        cells, shares, _ = row(cd.show(m), d, s, None, d.p, 5100 + i)
        G.model_cell(m, 0, cells[1], "Pays at p=0")
        G.model_cell(m, 4, cells[4], "Lost (%)")
        G.model_cell(m, 5, labels[max(shares, key=shares.get)], "Main loss")
        body.append(" & ".join(cells) + r" \\")
    strata_p = base_u.model + "|" + base_u.p.astype(str)
    cells, shares, (plo, phi) = row(r"\emph{Panel}", base_u, base_s,
                                    base_u[base_u.p == 0].model, strata_p, 0)
    G.macro("GridZeroPaying", cells[3].split("/")[0])
    G.macro("GridZeroSeats", cells[3].split("/")[1])
    G.macro("GridLossPanelPct", cells[4])
    body += [r"\midrule", " & ".join(cells) + r" \\"]
    head = [r" & \multicolumn{3}{c}{At $p{=}0$} & \multicolumn{2}{c}{Payoff lost} & "
            r"\multicolumn{3}{c}{Share of the loss (\%)} \\",
            r"\cmidrule(lr){2-4}\cmidrule(lr){5-6}\cmidrule(l){7-9}",
            r" & Mean & & Seats & & & Below & Past & Missed \\",
            r"Model & total & 95\% CI & paying & \% & 95\% CI & $p^*$ & 120 & at $p \ge p^*$ \\"]
    emit("s_grid_models.tex", "@{}lrlrrlrrr@{}", head, body)
    S.add("SupGridLostPanelLo", rnd(plo, 0))
    S.add("SupGridLostPanelHi", rnd(phi, 0))
    S.add("SupGridLossShareBelow", pc(shares["B"]))
    S.add("SupGridLossSharePast", pc(shares["A"]))
    S.add("SupGridLossShareMissed", pc(shares["C"]))


def t_endgame(games, G, S):
    base = games[games.exp == BASE]
    cols = {k: [] for k in ("z10", "sec_pct", "sec_n", "piv_pct", "piv_n", "two19", "reach_n",
                            "round", "waste", "miss", "pace", "reach_pct", "cf")}
    na = "n/a"
    tot_miss = tot_pace = 0
    for m in MODELS:
        g = selfplay_games(games, BASE, m)
        if len(g) != 110:
            raise RuntimeError(f"{m}: {len(g)} grid games")
        X = stack(g)
        pot = np.cumsum(X.sum(1), axis=1)
        z10 = X[:, :, 9] == 0
        p9 = pot[:, 8]
        sec9 = p9 >= cd.TARGET
        piv9 = (p9 >= 96) & (p9 < cd.TARGET)
        cols["z10"].append(pc(z10.mean()))
        cols["sec_pct"].append(pc(z10[sec9].mean()) if sec9.any() else na)
        cols["sec_n"].append(str(int(sec9.sum())))
        cols["piv_pct"].append(pc(z10[piv9].mean()) if piv9.any() else na)
        cols["piv_n"].append(str(int(piv9.sum())))
        cols["two19"].append(pc((X[:, :, :9] == 2).mean()))
        reached = pot[:, -1] >= cd.TARGET
        if not np.array_equal(reached, g.reached.values == 1):
            raise RuntimeError(f"{m}: pool and target flag disagree")
        cols["reach_n"].append(str(int(reached.sum())))
        cols["reach_pct"].append(pc(reached.mean()))
        pot_start = np.concatenate([np.zeros((len(g), 1)), pot[:, :-1]], axis=1)
        waste = (X.sum(1) * (pot_start >= cd.TARGET)).sum(1) / cd.N_PLAYERS
        if reached.any():
            secured = np.array([np.argmax(r >= cd.TARGET) + 1 for r in pot[reached]])
            cols["round"].append(rnd(secured.mean(), 1))
            cols["waste"].append(rnd(waste[reached].mean(), 1))
        else:
            cols["round"].append(na)
            cols["waste"].append(na)
        pos = g.p.values > 0
        miss = pos & ~reached
        on_pace = np.array([all(pt[t - 1] >= 12 * t for t in range(1, 10)) for pt in pot])
        cols["miss"].append(str(int(miss.sum())))
        cols["pace"].append(str(int((miss & on_pace).sum())))
        tot_miss += int(miss.sum())
        tot_pace += int((miss & on_pace).sum())
        Xcf = X.copy()
        Xcf[:, :, 9] = Xcf[:, :, 8]
        cols["cf"].append(pc((Xcf.sum(axis=(1, 2)) >= cd.TARGET).mean()))
        if m == "Qwen":
            G.macro("GridQwenLastZeroPct", cols["z10"][-1])
            G.macro("GridQwenRoundsOneNinePct", cols["two19"][-1])
            G.macro("GridQwenReach", cols["reach_n"][-1])
            G.macro("GridQwenFixReachPct", cols["cf"][-1])
            # The paper says paying nothing in round 10 is also an equilibrium of that round
            # for almost every Qwen3-235B table: true exactly when the pool after round 9 is
            # short of 120 by more than the 4 units one seat can add.
            beyond_one = (p9 < cd.TARGET) & (cd.TARGET - p9 > 4)     # 4: most one seat can pay
            S.add("SupQwenShortBeyondOne", str(int(beyond_one.sum())))
            S.add("SupQwenModalPoolNine", str(int(np.bincount(p9.astype(int)).argmax())))
        if m == "Grok":
            G.macro("GridGrokSecuredRound", cols["round"][-1])
            G.macro("GridGrokWaste", rnd(waste.mean(), 1))       # the paper averages all games
            G.check("Grok waste over reached games equals all games", cols["waste"][-1], rnd(waste.mean(), 1))
        if m == "Haiku":
            G.macro("GridHaikuStopPct", cols["sec_pct"][-1])
            G.macro("GridHaikuStopOtherPct", cols["piv_pct"][-1])
            S.add("SupHaikuStopGames", cols["sec_n"][-1])
            S.add("SupHaikuStopOtherGames", cols["piv_n"][-1])
        if m == "Luna":
            G.macro("GridLunaMiss", cols["miss"][-1])
            G.macro("GridLunaGames", str(int(pos.sum())))
        G.model_cell(m, 2, cols["reach_pct"][-1], "Target (%)")
    G.macro("GridMissTotal", str(tot_miss))
    G.macro("GridMissOnPace", str(tot_pace))

    def r(label, key):
        return label + " & " + " & ".join(cols[key]) + r" \\"

    body = [
        r("Seats paying 0 in round 10 (\\%)", "z10"),
        r("\\quad when the pool after round 9 is at least 120 (\\%)", "sec_pct"),
        r("\\qquad games in this case", "sec_n"),
        r("\\quad when it is 96 to 118 (\\%)", "piv_pct"),
        r("\\qquad games in this case", "piv_n"),
        r("Decisions paying 2 in rounds 1 to 9 (\\%)", "two19"),
        r"\addlinespace",
        r("Games reaching 120 (of 110)", "reach_n"),
        r("\\quad mean round the pool first reached 120", "round"),
        r("\\quad units per seat paid after that round", "waste"),
        r("Games missing 120 at $p>0$ (of 100)", "miss"),
        r("\\quad of which at or ahead of fair pace through round 9", "pace"),
        r"\addlinespace",
        r("Games reaching 120 as played (\\%)", "reach_pct"),
        r("\\quad had every seat repeated its round-9 move in round 10 (\\%)", "cf"),
    ]
    emit("s_endgame.tex", "@{}l" + "r" * len(MODELS) + "@{}", model_header(), body)


def endpoint_units(units, e):
    d = units[(units.exp == e) & units.p.isin(ENDPOINTS)]
    cnt = d.groupby(["model", "p"]).size()
    if len(cnt) != 2 * len(MODELS) or (cnt != 10).any():
        raise RuntimeError(f"{e}: expected 10 games per model at p = 0.1 and 0.9")
    return d


def t_controls_shift(units, G, S):
    sp._OFFSET[0] = 6000
    base = endpoint_units(units, BASE)
    body = []
    n_bold = 0
    for k, m in enumerate(MODELS):
        b = base[base.model == m]
        base_val = rnd(b.own.mean(), 1)
        G.robust_cell("Base", m, base_val, False)
        if k:
            body.append(r"\midrule")
        body.append(f"{cd.show(m)} & Base grid & {base_val} & & & \\\\")
        for name, e in CONTROLS:
            d = endpoint_units(units, e)
            d = d[d.model == m]
            diff, pv = sp.strat_perm(b.own, b.p, d.own, d.p)
            lo, hi = sp.strat_boot_diff_ci(b.own, b.p, d.own, d.p)
            bold = pv < 0.01 and abs(diff) >= 2.0
            n_bold += bold
            val = rnd(d.own.mean(), 1)
            row = next(r for r, ex in ROBUST_ROWS.items() if ex == e)
            G.robust_cell(row, m, val, bold)
            shift = f"\\textbf{{{rnd(diff, 1)}}}" if bold else rnd(diff, 1)
            body.append(f" & {name} & {val} & {shift} & {ci(lo, hi)} & {fmt_p(pv)} \\\\")
    head = [r" & & Mean seat & Shift from & & \\",
            r"Model & Condition & total & base grid & 95\% CI & $P$ \\"]
    emit("s_controls_shift.tex", "@{}llrrlr@{}", head, body)
    S.add("SupShiftBoldCount", str(n_bold))


def t_controls_goal(units, seats, G, S):
    arms = [("Base grid", BASE), ("Neutral wording", "exp_wording"), ("Goal stated", "exp_neutral")]
    body = []
    offset = 7000
    paying0 = {e: 0 for _, e in arms}
    for j, p in enumerate((0.0, 0.1, 0.9)):
        if j:
            body.append(r"\midrule")
        body.append(f"\\multicolumn{{11}}{{@{{}}l}}{{$p = {p:g}$}} \\\\")
        for m in MODELS:
            cells = [r"\quad " + cd.show(m)]
            own = {}
            for _, e in arms:
                d = units[(units.exp == e) & (units.model == m) & (units.p == p)]
                s = seats[(seats.exp == e) & (seats.model == m) & (seats.p == p)]
                if len(d) != 10 or len(s) != 60:
                    raise RuntimeError(f"{e} {m} p={p}: {len(d)} games, {len(s)} seats")
                own[e] = d.own
                paying = int((s.own > 0).sum())
                if p == 0:
                    paying0[e] += paying
                cells += [rnd(d.own.mean(), 1), str(int(d.reached.sum())), str(paying)]
                key = m.replace("-", "")
                label = {0.0: "Zero", 0.1: "Low", 0.9: "High"}[p]
                if e == BASE and p == 0:
                    G.macro("GridZero" + key, cells[-3])
                elif e == "exp_wording":
                    G.macro("Wor" + label + key, cells[-3])
                elif e == "exp_neutral":
                    G.macro("Neu" + label + key, cells[-3])
            offset += 1
            cells.append(fmt_p(cd.perm_test(own["exp_wording"], own["exp_neutral"], offset=offset)))
            body.append(" & ".join(cells) + r" \\")
    for m in MODELS:
        key = m.replace("-", "")
        for e, prefix in (("exp_wording", "Wor"), ("exp_neutral", "Neu")):
            d = units[(units.exp == e) & (units.model == m)]
            G.macro(prefix + "Reach" + key, str(int(d.reached.sum())))
    G.macro("GridZeroPaying", str(paying0[BASE]))
    G.macro("WorZeroPaying", str(paying0["exp_wording"]))
    G.macro("NeuZeroPaying", str(paying0["exp_neutral"]))
    head = [r" & \multicolumn{3}{c}{Base grid} & \multicolumn{3}{c}{Neutral wording} & "
            r"\multicolumn{3}{c}{Goal stated} & \\",
            r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}",
            r" & Mean & Target & Seats & Mean & Target & Seats & Mean & Target & Seats & $P$, neutral \\",
            r"Model & total & (of 10) & paying & total & (of 10) & paying & total & (of 10) & paying & vs goal \\"]
    emit("s_controls_goal.tex", "@{}l" + "rrr" * 3 + "r@{}", head, body)
    s1 = seats[(seats.exp == "exp_neutral") & (seats.p == 0.1) & (seats.model == "Luna")]
    S.add("SupGoalLowPayingLuna", str(int((s1.own > 0).sum())))


def t_controls_detail(games, units, seats, G, S):
    conds = [("Base grid", BASE), *CONTROLS]
    macro_q = {BASE: "RobQwenLastZeroBase", "exp_nohint": "RobQwenLastZeroNoHint",
               "exp_para1": "RobQwenLastZeroParaOne", "exp_para2": "RobQwenLastZeroParaTwo",
               "exp_neutral": "RobQwenLastZeroNeutral", "exp_wording": "RobQwenLastZeroWording"}
    macro_g = {BASE: "RobGrokRiskBase", "exp_para2": "RobGrokRiskParaTwo", "exp_evprobe": "RobGrokRiskRerun"}
    macro_d = {BASE: "RobTempZeroBaseDistinct", "exp_baseline_temp0": "RobTempZeroDistinct"}
    body = []
    for i, (name, e) in enumerate(conds):
        s = seats[(seats.exp == e) & seats.p.isin(ENDPOINTS)]

        def share(m, fn):
            x = s[s.model == m]
            if len(x) != 120:
                raise RuntimeError(f"{e} {m}: {len(x)} endpoint seats")
            return pc(x.traj.map(fn).mean())

        q = share("Qwen", lambda t: t[-1] == 0)
        fl = share("Flash-Lite", lambda t: all_equal(t, 2))
        lu = share("Luna", lambda t: all_equal(t, 2))
        gk = share("Grok", lambda t: all_equal(t, 4))
        u = endpoint_units(units, e)
        g1 = u[(u.model == "Grok") & (u.p == 0.1)].own
        g9 = u[(u.model == "Grok") & (u.p == 0.9)].own
        step = rnd(g9.mean() - g1.mean(), 1)
        pv = cd.perm_test(g1, g9, offset=7100 + i)
        gg = games[(games.exp == e) & games.p.isin(ENDPOINTS)]
        per_cell = gg.groupby(["folder_model", "p"]).strat.apply(
            lambda col: len({tuple(map(tuple, x.astype(int))) for x in col}))
        if len(per_cell) != 2 * len(MODELS):
            raise RuntimeError(f"{e}: {len(per_cell)} endpoint cells")
        dist = rnd(per_cell.mean(), 1)
        if e in macro_q:
            G.macro(macro_q[e], q)
        if e in macro_g:
            G.macro(macro_g[e], step)
        if e == BASE:
            S.add("SupGrokStepBaseP", fmt_p(pv))
        if e == "exp_baseline_temp0":
            S.add("SupGrokStepTempZero", step)
            S.add("SupGrokStepTempZeroP", fmt_p(pv))
        if e in macro_d:
            G.macro(macro_d[e], dist)
        body.append(f"{name} & {q} & {fl} & {lu} & {gk} & {step} & {fmt_p(pv)} & {dist} \\\\")
        if e == "exp_baseline_temp0":
            S.add("SupTempZeroDistinctMin", str(int(per_cell.min())))
            S.add("SupTempZeroDistinctMax", str(int(per_cell.max())))
    fam = {m: cd.LINES[m][0] for m in MODELS}
    mem = {m: cd.LINES[m][1] for m in MODELS}
    head = [f" & {fam['Qwen']} & {fam['Flash-Lite']} & {fam['Luna']} & \\multicolumn{{3}}{{c}}{{{cd.show('Grok')}}} & \\\\",
            f" & {mem['Qwen']} & {mem['Flash-Lite']} & {mem['Luna']} & & & & \\\\",
            r"\cmidrule(lr){2-2}\cmidrule(lr){3-3}\cmidrule(lr){4-4}\cmidrule(lr){5-7}",
            r" & Pays 0 in & Exact & Exact & Pays 4 in & Total at 0.9 & & Distinct \\",
            r"Condition & round 10 (\%) & split (\%) & split (\%) & every round (\%) & minus at 0.1 & $P$ & games \\"]
    emit("s_controls_detail.tex", "@{}lrrrrrrr@{}", head, body)


