def selfplay_games(games, exp, m):
    return games[(games.exp == exp) & games.models.map(lambda t, m=m: t == (m,))]


def stack(g):
    return np.stack(g.strat.to_list()).astype(int)                 # games x 6 x 10


def all_equal(traj, value):
    return all(a == value for a in traj)


