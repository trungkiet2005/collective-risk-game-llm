def main():
    gate = Gate()
    tabs = Tables()
    snum = {}

    mg, mu, su = mx_mod.load()
    mx_mod.check_design(mg, mu, su)
    mx, sp = sel.load()
    if len(mx) != len(mg) or set(mx.gid) != set(mg.gid):
        raise RuntimeError("the two loaders see different mixed games")

    tabs.add("s_mix_reach.tex", r"@{}ll*{6}{r}@{}", t_reach(mg, gate))
    tabs.add("s_mix_reach_p.tex", r"@{}llrrr@{}", t_reach_p(mg, su))
    edge_lines, mats = t_edge(mx, sp, gate)
    tabs.add("s_mix_edge.tex", r"@{}l*{5}{c}@{}", edge_lines)
    tabs.add("s_mix_pairs.tex", r"@{}l*{5}{c}@{}", t_pairs(mats, gate))
    tabs.add("s_mix_lastround.tex", r"@{}lrrr@{}", t_lastround(mg, gate, snum))
    tabs.add("s_mix_slack.tex", r"@{}l*{6}{c}@{}", t_slack(mg, mu, su, gate))
    tabs.add("s_mix_timing.tex", r"@{}l*{9}{r}@{}", t_timing(mg, gate, snum))

    sel.identity_check(mx)
    mixed, selfc = sel.cell_arrays(mx, sp)
    # Same generator offsets as selection.main(); the replicates depend only on the draws in
    # selection.tables(), so boot_extra=False gives the paper's replicates for the two rules.
    runs = {"pooled": sel.run_rules(mixed, selfc, "POOLED self-play", offset=1, boot_extra=False)}
    _, selfc_base = sel.cell_arrays(mx, sp[sp.exp == "exp_baseline"])
    runs["base"] = sel.run_rules(mixed, selfc_base, "grid-only self-play", offset=2, boot_extra=False)
    P, REACH, WEL, point, boots = runs["pooled"]
    for pi, p in enumerate(RISKS):
        tabs.add(f"s_sel_payoff_p{int(round(10 * p)):02d}.tex", r"@{}ll*{6}{r}@{}", t_payoff(P, pi))
    tabs.add("s_sel_mass.tex", r"@{}lrr*{5}{c}rr@{}", t_mass(P, REACH, WEL, point, gate, snum))
    tabs.add("s_sel_boot.tex", r"@{}lrlrrcrc@{}", t_boot(runs, gate, snum))
    tabs.add("s_sel_facts.tex", r"@{}lrrrl@{}", t_facts(mx, P, gate, snum))

    # all gates passed: write
    tabs.write()
    lines = [HEADER]
    for key, value in snum.items():
        if not re.fullmatch(r"Sup[A-Za-z]+", key):
            raise ValueError(f"macro name {key!r}")
        lines.append(f"\\newcommand{{\\{key}}}{{{value}}}")
    (OUT_TABLES / "snum_groups.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {(OUT_TABLES / 'snum_groups.tex').relative_to(cd.REPO)}")
    for key, value in snum.items():
        print(f"  \\{key} = {value}")
    print(f"consistency gate: {len(set(gate.checked))} paper macros match: {', '.join(sorted(set(gate.checked)))}")

    fig = figure(P)
    pdf = cs.save(fig, OUT_FIGURES / "sfig_mass_beta", title="sfig_mass_beta")
    print(f"wrote {pdf.relative_to(cd.REPO)} (+ .png)")


if __name__ == "__main__":
    main()
