def figure(P):
    cs.use()
    fig = plt.figure(figsize=cs.figsize("full", height_pt=270), layout="none")
    # A figure without an engine gets one back from rcParams (constrained, set by cs.use())
    # after its first savefig, which would re-lay the grid out between the PDF and the PNG.
    fig.set_layout_engine(PlaceHolderLayoutEngine(adjust_compatible=True, colorbar_gridspec=True))
    fig._crsd_width = "full"
    grid = fig.add_gridspec(2, 3, left=0.075, right=0.985, bottom=0.125, top=0.865, wspace=0.35, hspace=0.55)
    letters = iter("abcdef")
    colours = [cs.model(m).colour for m in M]
    worst = 0.0
    for ri, (rule, N) in enumerate((("within", sel.N_WITHIN), ("across", sel.N_ACROSS))):
        for ci, p in enumerate(RISKS):
            ax = fig.add_subplot(grid[ri, ci])
            mass = np.array([tree_mass(log_rho(P[ci], rule, N, b)) for b in BETA_GRID])
            for b, row in zip(BETA_GRID, mass):
                o = sel.outcome(P[ci], np.zeros(K), np.zeros(K), rule, b, N)
                if o["n_unit"] == 1:
                    worst = max(worst, float(np.abs(o["pi"] - row).max()))
            ax.stackplot(BETA_GRID, mass.T, colors=colours, edgecolor=cs.WHITE, linewidth=0.25, zorder=2)
            ax.axvline(sel.BETA, **{k: v for k, v in cs.THEORY.items() if k != "marker"})
            ax.set_xscale("log")
            ax.set_xlim(BETA_GRID[0], BETA_GRID[-1])
            ax.set_ylim(0, 1)
            ax.set_xticks([0.01, 0.1, 1, 10, 100], ["0.01", "0.1", "1", "10", "100"])
            ax.get_xticklabels()[0].set_horizontalalignment("left")    # clear of the y label "0"
            ax.xaxis.set_minor_locator(NullLocator())
            ax.set_yticks([0, 0.5, 1], ["0", "0.5", "1"])
            ax.grid(False)
            cs.panel_title(ax, next(letters), f"{RULE_NAME[rule]}, $N={N}$, $p={p:g}$")
            if ri == 1:
                ax.set_xlabel(r"Selection intensity $\beta$")
            if ci == 0:
                ax.set_ylabel("Stationary mass")
    if worst > 1e-6:
        raise RuntimeError(f"figure: tree theorem and eigen solver differ by {worst:.2e} on well-conditioned chains")
    print(f"figure: tree theorem vs eigen solver on well-conditioned chains, max abs difference {worst:.1e}")
    handles = [Patch(facecolor=c, edgecolor="none", label=show(m)) for m, c in zip(M, colours)]
    fig.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.5, 0.995), ncols=K, frameon=False,
               handlelength=1.1, handleheight=0.8, columnspacing=1.4)
    return fig


