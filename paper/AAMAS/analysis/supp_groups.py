"""Supplementary tables for two models at one table and for selection among the models.

Run from the repository root (the selection bootstrap takes a few minutes):
    python paper/AAMAS/analysis/supp_groups.py

Reads results/exp_mixed, results/exp_baseline and results/exp_evprobe through the loaders of
mixed.py and selection.py (read-only; never Legacy_Results/, never writes under results/).
No module's main(), figure() or draw() is called, so the paper's figures and num_*.tex
macro files are left untouched. Writes ONLY
    paper/AAMAS/supplement/tables/s_mix_*.tex, s_sel_*.tex   (booktabs tabulars, no float)
    paper/AAMAS/supplement/tables/snum_groups.tex            (\\newcommand macros, prefix Sup)
    paper/AAMAS/supplement/figures/sfig_mass_beta.pdf (+ .png preview)

NUMBERS
    Unit = game. Payoffs are EXPECTED payoffs over the catastrophe lottery (crsd_data).
    Intervals are 95% percentile bootstraps over games. A number that the paper already
    prints is recomputed with the module's own bootstrap offset; new intervals use offsets
    >= 8000. Rounding is half-up on the decimal value.
    Before any file is written, every printed value that also exists in
    tables/num_mixed.tex, num_advantage.tex or num_selection.tex is compared with the macro
    at the macro's precision; a difference raises RuntimeError.

STATIONARY MASS
    Every mass in the tables is selection.outcome() (eigenvector of the embedded chain), as
    in the paper. Under strong selection some fixation probabilities fall below 1e-9 and
    the eigen solver sees more than one unit eigenvalue. Every mass is therefore recomputed
    with the Markov chain tree theorem in log space (exact for any beta), and the script
    refuses to write a table whose printed values the two methods do not share. The figure
    uses the tree theorem, checked against the eigen solver wherever the chain is well
    conditioned.
"""
