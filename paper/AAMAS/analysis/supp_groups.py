def t_payoff(P, pi):
    lines = [r"Model & Beside & \multicolumn{6}{c}{Seats of the model at the table} \\",
             r"\cmidrule(l){3-8}",
             r" & & 1 & 2 & 3 & 4 & 5 & 6 \\",
             r"\midrule"]
    for xi, x in enumerate(M):
        partners = [y for y in M if y != x]
        for yi, y in enumerate(partners):
            vals = [P[pi, MI[x], MI[y], k] for k in range(1, 7)]
            if np.isnan(vals).any():
                raise RuntimeError(f"payoff function {x} beside {y} at p={RISKS[pi]} has a gap")
            end = r" \\[3pt]" if (yi == len(partners) - 1 and xi < K - 1) else r" \\"
            lines.append(f"{show(x) if yi == 0 else ''} & {show(y)} & " + " & ".join(num(v, 2) for v in vals) + end)
        if len({P[pi, MI[x], MI[y], 6] for y in partners}) != 1:
            raise RuntimeError(f"{x}: self-play entry differs across partners")
    return lines


def t_mass(P, REACH, WEL, point, gate, snum):
    lines = [r" & & & " + " & ".join(cd.LINES[m][0] for m in M) + r" & Target & Payoff \\",
             r"Population & $N$ & $\beta$ & " + " & ".join(cd.LINES[m][1] for m in M) + r" & (\%) & per seat \\",
             r"\midrule"]
    reducible, results = 0, {}
    for pi, p in enumerate(RISKS):
        if pi:
            lines.append(r"\midrule")
        lines.append(group(f"$p={p:g}$", 10))
        prev_rule = None
        for rule, beta, N in MASS_SPECS:
            o, exact = outcome_checked(P[pi], REACH[pi], WEL[pi], rule, beta, N)
            key = (rule, beta, N, pi)
            if key in point and not np.allclose(point[key]["pi"], o["pi"]):
                raise RuntimeError(f"{key}: mass disagrees with selection.run_rules")
            reducible += int(o["n_unit"] != 1)
            results[key] = o
            label = RULE_NAME[rule] if rule != prev_rule else ""
            prev_rule = rule
            lines.append(f"{label} & {N} & {beta:g} & " + " & ".join(num(v, 2) for v in o["pi"])
                         + f" & {pct(o['reach'])} & {num(o['pay'], 1)} \\\\")
        lines.append(r"Random model & & & " + " & ".join(num(1 / K, 2) for _ in M)
                     + f" & {pct(REACH[pi].mean())} & {num(WEL[pi].mean(), 1)} \\\\")
    lo, mid, hi = RISKS.index(0.1), RISKS.index(0.5), RISKS.index(0.9)
    for name, i in (("Low", lo), ("Mid", mid), ("High", hi)):
        gate.number(f"SelWithinQwenMass{name}", results[("within", 1.0, 6, i)]["pi"][MI["Qwen"]])
    gate.number("SelWithinReachHigh", 100 * results[("within", 1.0, 6, hi)]["reach"])
    gate.number("SelWithinReachMid", 100 * results[("within", 1.0, 6, mid)]["reach"])
    gate.number("SelWithinPayHigh", results[("within", 1.0, 6, hi)]["pay"])
    gate.number("SelAcrossFlashMassMid", results[("across", 1.0, 30, mid)]["pi"][MI["Flash-Lite"]])
    gate.number("SelAcrossFlashMassHigh", results[("across", 1.0, 30, hi)]["pi"][MI["Flash-Lite"]])
    gate.number("SelAcrossReachHigh", 100 * results[("across", 1.0, 30, hi)]["reach"])
    gate.number("SelAcrossPayHigh", results[("across", 1.0, 30, hi)]["pay"])
    gate.text("SelAcrossWinnerLow", show(M[results[("across", 1.0, 30, lo)]["top"]]))
    gate.number("SelUniformReachHigh", 100 * REACH[hi].mean())
    gate.number("SelUniformReachMid", 100 * REACH[mid].mean())
    gate.number("SelStrongWithinReachMid", 100 * results[("within", 10.0, 6, mid)]["reach"])
    gate.number("SelStrongWithinReachHigh", 100 * results[("within", 10.0, 6, hi)]["reach"])
    gate.number("SelWeakWithinMaxMass", max(float(results[("within", 0.1, 6, i)]["pi"].max()) for i in range(3)))
    gate.text("SelWeakAcrossTopHigh", show(M[results[("across", 0.1, 30, hi)]["top"]]))
    gate.text("SelWeakAcrossTopMid", show(M[results[("across", 0.1, 30, mid)]["top"]]))
    for (rule, beta, N) in MASS_SPECS:
        for i in range(3):
            ref = results[(rule, 1.0, 6 if rule == "within" else 30, i)]["top"]
            if beta != 0.1 and results[(rule, beta, N, i)]["top"] != ref:
                raise RuntimeError(f"winner changes under {(rule, beta, N)} at p={RISKS[i]}")
    snum["SupSelWeakWithinTopMid"] = show(M[results[("within", 0.1, 6, mid)]["top"]])
    snum["SupSelWeakWithinTopHigh"] = show(M[results[("within", 0.1, 6, hi)]["top"]])
    snum["SupSelIllConditioned"] = str(reducible)
    print(f"mass table: {reducible} rows where the eigen solver sees more than one unit eigenvalue; "
          "the tree theorem prints the same values")
    return lines


def t_boot(runs, gate, snum):
    lines = [r"Population & $p$ & Top model & Top in (\%) & Target (\%) & 95\% CI & Payoff per seat & 95\% CI \\",
             r"\midrule"]
    winners = {}
    for si, (source, (P, REACH, WEL, point, boots)) in enumerate(runs.items()):
        if si:
            lines.append(r"\midrule")
        lines.append(group(SELF_SOURCE[source], 8))
        shares = []
        for rule, beta, N in sel.RULES:
            for pi, p in enumerate(RISKS):
                o = point[(rule, beta, N, pi)]
                bs = boots[(rule, beta, N, pi)]
                if len(bs) != sel.N_BOOT:
                    raise RuntimeError(f"{source} {rule} p={p}: {len(bs)} bootstrap replicates")
                share = float(np.mean([b["top"] == o["top"] for b in bs]))
                shares.append(share)
                rlo, rhi = np.percentile([b["reach"] for b in bs], [2.5, 97.5])
                wlo, whi = np.percentile([b["pay"] for b in bs], [2.5, 97.5])
                winners[(source, rule, pi)] = o["top"]
                label = RULE_NAME[rule] if pi == 0 else ""
                lines.append(f"{label} & {p:g} & {show(M[o['top']])} & {pct(share)} & {pct(o['reach'])} & "
                             f"{interval(rlo, rhi, 0, 100)} & {num(o['pay'], 1)} & {interval(wlo, whi, 1)} \\\\")
        if source == "pooled":
            gate.number("SelBootMinPct", 100 * min(shares))
        else:
            snum["SupSelBaseBootMinPct"] = pct(min(shares))
    for rule, _, _ in sel.RULES:
        for pi in range(3):
            if winners[("pooled", rule, pi)] != winners[("base", rule, pi)]:
                raise RuntimeError(f"{rule} p={RISKS[pi]}: winner changes with the self-play source")
    snum["SupSelBootReps"] = thousands(sel.N_BOOT)
    return lines


def t_facts(mx, P, gate, snum):
    wins, below, n_cells, above = sel.table_facts(mx)
    lines = [group("(a) One seat beside five Grok 4.20 seats: expected payoff per seat", 5),
             r"Model & $p$ & One seat & Grok 4.20 seats & Ahead \\",
             r"\midrule"]
    ahead = 0
    for m in M:
        if m == "Grok":
            continue
        for pi, p in enumerate(RISKS):
            d = mx[(mx.p == p) & (((mx.A == m) & (mx.B == "Grok") & (mx.kA == 1))
                                  | ((mx.B == m) & (mx.A == "Grok") & (mx.kA == 5)))]
            if len(d) != 10:
                raise RuntimeError(f"{m} beside five Grok seats at p={p}: {len(d)} games")
            em = float(np.where(d.A == m, d.eA, d.eB).mean())
            eg = float(np.where(d.A == "Grok", d.eA, d.eB).mean())
            if abs(em - P[pi, MI[m], MI["Grok"], 1]) > 1e-12 or abs(eg - P[pi, MI["Grok"], MI[m], 5]) > 1e-12:
                raise RuntimeError(f"{m} beside five Grok seats disagrees with the payoff functions")
            if rnd(em, 2) == rnd(eg, 2):
                raise RuntimeError(f"{m} vs Grok at p={p}: tie at printed precision")
            ahead += int(em > eg)
            lines.append(f"{show(m) if pi == 0 else ''} & {p:g} & {num(em, 2)} & {num(eg, 2)} & "
                         f"{'One seat' if em > eg else show('Grok')} \\\\")
    if ahead != wins:
        raise RuntimeError("single-seat wins disagree with selection.table_facts")
    gate.number("SelGrokLosesCells", wins)

    lines += [r"\midrule",
              group(f"(b) {show('Qwen')} against its tablemates, exact one-sided sign-flip test per cell, "
                    f"$\\alpha={sel.ALPHA_SIG:g}$", 5),
              rf"\multicolumn{{4}}{{@{{}}l}}{{Cells (pair, seats, $p$) with {show('Qwen')} seats}} & {n_cells} \\",
              rf"\multicolumn{{4}}{{@{{}}l}}{{\quad {show('Qwen')} significantly below its tablemates}} & {len(below)} \\",
              rf"\multicolumn{{4}}{{@{{}}l}}{{\quad {show('Qwen')} significantly above its tablemates}} & {above} \\"]
    for c in below:
        other = c["B"] if c["A"] == "Qwen" else c["A"]
        q = c["qwen_seats"]
        lines.append(rf"\multicolumn{{5}}{{@{{}}l}}{{\quad\quad Below: $p={c['p']:g}$, {cd.word(q)} {show('Qwen')} "
                     rf"seat{'s' if q > 1 else ''} beside {cd.word(6 - q)} {show(other)} seat{'s' if 6 - q > 1 else ''}, "
                     rf"payoff gap {num(c['gap'], 2)}, one-sided $P={num(c['p_one_sided'], 3)}$}} \\")
    gate.number("SelQwenCells", n_cells)
    gate.text("SelQwenBelowCells", cd.word(len(below)))
    gate.number("SelQwenAboveCells", above)

    lines += [r"\midrule",
              group(r"(c) Winner by population size, $\beta=1$, $N$ from 6 to 120", 5),
              r"$p$ & \multicolumn{2}{l}{Winner at smaller $N$} & From $N$ & Winner up to $N=120$ \\",
              r"\midrule"]
    for pi, p in enumerate(RISKS):
        tops = {}
        for N in sel.N_SCAN:
            R = sel.rho_matrix(P[pi], N, sel.BETA)
            eig_top = int(np.argmax(sel.stationary(R)[0]))
            if eig_top != int(np.argmax(tree_mass(log_rho(P[pi], "across", N, sel.BETA)))):
                raise RuntimeError(f"p={p} N={N}: eigen solver and tree theorem pick different winners")
            tops[N] = M[eig_top]
        final = tops[max(sel.N_SCAN)]
        start = min(N for N in sel.N_SCAN if all(tops[n] == final for n in sel.N_SCAN if n >= N))
        if start != sel.switch_n(P, pi, target=final):
            raise RuntimeError(f"p={p}: population-size scan disagrees with selection.switch_n")
        earlier = [N for N in sel.N_SCAN if N < start]
        if earlier:
            names = sorted({tops[N] for N in earlier}, key=M.index)
            span = f"$N={earlier[0]}$" if len(earlier) == 1 else f"$N={earlier[0]}$ to ${earlier[-1]}$"
            before = ", ".join(show(n) for n in names) + f" ({span})"
        else:
            before = "none"
        lines.append(rf"{p:g} & \multicolumn{{2}}{{l}}{{{before}}} & {start} & {show(final)} \\")
        if p == 0.9:
            gate.number("SelSwitchN", start)
        if p == 0.5:
            snum["SupSelSwitchNMid"] = str(start)
    return lines


