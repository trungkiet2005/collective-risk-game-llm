# ============================================================================ formatting
def rnd(x: float, digits: int) -> Decimal:
    """Half-up rounding of the decimal value (binary noise below 1e-12 is ignored)."""
    v = Decimal(f"{float(x):.12f}").quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_UP)
    return abs(v) if v == 0 else v


def num(x: float, digits: int = 1, plus: bool = False) -> str:
    v = rnd(x, digits)
    s = f"{abs(v):.{digits}f}"
    if v < 0:
        return "$-$" + s
    return ("$+$" + s) if (plus and v > 0) else s


def pct(share: float, digits: int = 0) -> str:
    return num(100.0 * share, digits)


def interval(lo: float, hi: float, digits: int = 1, scale: float = 1.0) -> str:
    return f"[{num(scale * lo, digits)}, {num(scale * hi, digits)}]"


def thousands(n: int) -> str:
    return f"{int(n):,}".replace(",", "{,}")


def show(m: str) -> str:
    return cd.show(m)


def model_header(first: str = "", n_before: int = 1) -> list:
    """Two header rows with the five model names split over two lines (cd.LINES)."""
    pad = " & " * (n_before - 1)
    top = pad + " & " + " & ".join(cd.LINES[m][0] for m in M) + r" \\"
    bottom = first + pad + " & " + " & ".join(cd.LINES[m][1] for m in M) + r" \\"
    return [top, bottom]


def group(text: str, ncols: int) -> str:
    return rf"\multicolumn{{{ncols}}}{{@{{}}l}}{{\textit{{{text}}}}} \\"


# ============================================================================ consistency gate
class Gate:
    """Compare printed values with the paper's macros, at the macro's precision."""

    def __init__(self):
        self.macros = {}
        for name in MACRO_FILES:
            text = (cd.TABLES / name).read_text(encoding="utf-8")
            for key, value in re.findall(r"^\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}\s*$", text, re.M):
                self.macros[key] = value
        self.checked = []

    def number(self, name: str, value: float):
        if name not in self.macros:
            raise RuntimeError(f"gate: macro {name} not found in {MACRO_FILES}")
        raw = self.macros[name].replace("{,}", "").replace("$-$", "-")
        digits = len(raw.split(".")[1]) if "." in raw else 0
        mine = rnd(value, digits)
        if mine != Decimal(raw):
            raise RuntimeError(f"gate: \\{name} is {self.macros[name]} in the paper, this script prints {mine}")
        self.checked.append(name)

    def text(self, name: str, value: str):
        if self.macros.get(name) != value:
            raise RuntimeError(f"gate: \\{name} is {self.macros.get(name)!r} in the paper, this script prints {value!r}")
        self.checked.append(name)


# ============================================================================ writing
class Tables:
    def __init__(self):
        self.files = {}

    def add(self, name: str, colspec: str, lines: list):
        body = [HEADER, rf"\begin{{tabular}}{{{colspec}}}", r"\toprule", *lines, r"\bottomrule", r"\end{tabular}"]
        text = "\n".join(body) + "\n"
        if "--" in text or chr(0x2013) in text or chr(0x2014) in text:
            raise RuntimeError(f"{name}: a dash that renders as an en or em dash")
        if re.search(r"exp_|\.csv|\.py", text.split("\n", 1)[1]):
            raise RuntimeError(f"{name}: internal name in reader-facing text")
        rows = sum(1 for line in body if line.rstrip().endswith(r"\\"))
        if rows > MAX_ROWS:
            raise RuntimeError(f"{name}: {rows} rows, the limit is {MAX_ROWS}")
        self.files[name] = (text, rows)

    def write(self):
        OUT_TABLES.mkdir(parents=True, exist_ok=True)
        for name, (text, rows) in self.files.items():
            (OUT_TABLES / name).write_text(text, encoding="utf-8")
            print(f"wrote {(OUT_TABLES / name).relative_to(cd.REPO)} ({rows} rows)")


