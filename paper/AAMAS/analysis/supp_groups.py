def t_timing(mg, gate, snum):
    rows = []
    for g in mg.itertuples():                     # same definitions as mixed.timing_split
        if "Grok" not in (g.A, g.B):
            continue
        m = g.B if g.A == "Grok" else g.A
        idx = [i for i, name in enumerate(g.names) if name == m]
        pot_start = np.r_[0.0, np.cumsum(g.strat.sum(axis=0))[:-1]]
        before = pot_start < cd.TARGET
        sf = np.maximum(0.0, cd.FAIR_SHARE - g.strat[idx])
        rows.append(dict(model=m, early=sf[:, before].mean() if before.any() else np.nan,
                         late=sf[:, ~before].mean() if (~before).any() else np.nan,
                         tot_early=sf[:, before].sum(axis=1).mean(), tot_late=sf[:, ~before].sum(axis=1).mean()))
    T = pd.DataFrame(rows)
    ref = mx_mod.timing_split(mg)
    lines = [r" & \multicolumn{3}{c}{Before the pool reached 120} & \multicolumn{3}{c}{After the pool reached 120}"
             r" & \multicolumn{3}{c}{Units short per seat per game} \\",
             r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(l){8-10}",
             r"Model & Per round & 95\% CI & Games & Per round & 95\% CI & Games & Before & After & After (\%) \\",
             r"\midrule"]
    for mi, m in enumerate(FOCAL):
        d = T[T.model == m]
        if len(d) != 150:
            raise RuntimeError(f"{m} beside Grok: {len(d)} games")
        e, l = d.early.mean(), d.late.mean()
        if abs(e - ref[m]["early"]) > 1e-12 or abs(l - ref[m]["late"]) > 1e-12:
            raise RuntimeError(f"{m}: timing split disagrees with mixed.timing_split")
        e_ci = cd.boot_ci(d.early.dropna(), offset=400 + mx_mod.PANEL_B.index(m))
        l_ci = cd.boot_ci(d.late.dropna(), offset=8200 + mi)
        te, tl = d.tot_early.mean(), d.tot_late.mean()
        share = tl / (te + tl)
        lines.append(f"{show(m)} & {num(e, 2)} & {interval(*e_ci, 2)} & {d.early.count()} & {num(l, 2)} & "
                     f"{interval(*l_ci, 2)} & {d.late.count()} & {num(te, 1)} & {num(tl, 1)} & {pct(share)} \\\\")
        snum[f"SupMixTiming{cd.MACRO[m]}AfterPct"] = pct(share)
    gate.number("MixLunaEarlyShort", ref["Luna"]["early"])
    gate.number("MixFlashEarlyShort", ref["Flash-Lite"]["early"])
    gate.number("MixHaikuEarlyShort", ref["Haiku"]["early"])
    return lines


# ============================================================================ stationary mass, exact
def _arborescences():
    """For every root, the K^(K-2) spanning trees with all edges directed towards it."""
    out = {}
    for root in range(K):
        others = [u for u in range(K) if u != root]
        valid = []
        for parents in itertools.product(range(K), repeat=K - 1):
            par = dict(zip(others, parents))
            if any(par[u] == u for u in others):
                continue
            ok = True
            for u in others:
                v, steps = u, 0
                while v != root and steps <= K:
                    v, steps = par[v], steps + 1
                if v != root:
                    ok = False
                    break
            if ok:
                valid.append([(u, par[u]) for u in others])
        if len(valid) != K ** (K - 2):
            raise RuntimeError(f"root {root}: {len(valid)} arborescences, Cayley says {K ** (K - 2)}")
        out[root] = np.array(valid)
    return out


TREES = _arborescences()


def log_rho(Pp, rule, N, beta):
    """L[x, y] = log fixation probability of one x newcomer in a y population (selection.py's
    formula, kept in logs)."""
    L = np.full((K, K), np.nan)
    i = np.arange(1, sel.N_WITHIN)
    for x, y in itertools.permutations(range(K), 2):
        if rule == "within":
            fx, fy = Pp[x, y, i], Pp[y, x, sel.N_WITHIN - i]
        else:
            fx, fy = sel.fitness(Pp, x, y, N)
        L[x, y] = -logsumexp(np.r_[0.0, -beta * np.cumsum(fx - fy)])
    return L


def tree_mass(L):
    """Markov chain tree theorem: mass of state s is proportional to the sum, over trees
    directed into s, of the product of transition probabilities u -> parent(u), where the
    move from resident u to model v happens at rate rho[v, u] / (K - 1)."""
    logw = np.empty(K)
    for root, trees in TREES.items():
        u, v = trees[:, :, 0], trees[:, :, 1]
        logw[root] = logsumexp(L[v, u].sum(axis=1))
    return np.exp(logw - logsumexp(logw))


def outcome_checked(Pp, reach, wel, rule, beta, N):
    o = sel.outcome(Pp, reach, wel, rule, beta, N)
    exact = tree_mass(log_rho(Pp, rule, N, beta))
    same_print = (all(rnd(a, 2) == rnd(b, 2) for a, b in zip(o["pi"], exact))
                  and rnd(100 * o["reach"], 0) == rnd(100 * exact @ reach, 0)
                  and rnd(o["pay"], 1) == rnd(exact @ wel, 1)
                  and int(np.argmax(exact)) == o["top"])
    if not same_print:
        raise RuntimeError(f"{rule} beta={beta} N={N}: eigen solver {o['pi']} and tree theorem {exact} "
                           "print differently")
    if o["n_unit"] == 1 and not np.allclose(o["pi"], exact, atol=1e-8):
        raise RuntimeError(f"{rule} beta={beta} N={N}: tree theorem disagrees with a well-conditioned chain")
    return o, exact


