def t_edge(mx, sp, gate):
    edge, edge_ci, contrib_gap, reach, count, n = adv.matrices(mx, sp)
    lines = model_header("Row model") + [r"\midrule", group("Expected payoff per seat, row model minus column model", 6)]
    for i, m in enumerate(M):
        vals, cis = [], []
        for j in range(K):
            if i == j:
                vals.append(r"\textit{self}")
                cis.append("")
            else:
                vals.append(num(edge[i, j], 1, plus=True))
                cis.append(interval(*edge_ci[(i, j)], 1))
        lines.append(f"{show(m)} & " + " & ".join(vals) + r" \\")
        lines.append(" & " + " & ".join(cis) + (r" \\[2pt]" if i < K - 1 else r" \\"))
    lines += [r"\midrule", group("Units paid per seat, row model minus column model", 6)]
    for i, m in enumerate(M):
        vals = [r"\textit{self}" if i == j else num(contrib_gap[i, j], 1, plus=True) for j in range(K)]
        lines.append(f"{show(m)} & " + " & ".join(vals) + r" \\")
    # gate
    off = ~np.eye(K, dtype=bool)
    g, q = MI["Grok"], MI["Qwen"]
    grok_row = {M[j]: edge[g, j] for j in range(K) if j != g}
    worst = min(grok_row, key=grok_row.get)
    qwen_row = {M[j]: edge[q, j] for j in range(K) if j != q}
    best = max(qwen_row, key=qwen_row.get)
    gate.number("AdvGrokWorst", -grok_row[worst])
    gate.text("AdvGrokWorstPartner", show(worst))
    gate.number("AdvQwenBest", qwen_row[best])
    gate.text("AdvQwenBestPartner", show(best))
    gate.number("AdvMaxAbs", float(np.max(np.abs(edge[off]))))
    return lines, (edge, edge_ci, contrib_gap, reach, count, n)


