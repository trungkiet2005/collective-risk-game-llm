"""Supplementary tables (and one figure) for the in-game questions.

Run from the repository root:
    python paper/AAMAS/analysis/supp_probes.py

Reads results/exp_evprobe and results/exp_evprobe_probes.csv (read-only) through
crsd_data and probes (load, decode_value_compare, shifts). Never calls probes.main() or
probes.figure(), which rewrite the paper's own figure and macros.

Writes, into paper/AAMAS/supplement/tables/:
    s_probe_rules.tex   accuracy per rule question x model, with n per cell
    s_probe_value.tex   value comparison: A / B / equal counts and % correct, model x p
    s_probe_rounds.tex  share saying keeping pays more, model x p x round; games that change
    s_probe_defect.tex  second value question: % correct (by round), 40, cash-left reading, 0, other
    s_knowdo.tex        numbers behind the know-do scatter: levels and shifts with 95% CIs
and paper/AAMAS/supplement/figures/sfig_answers.pdf (+ .png).

Every value printed here that the paper also carries as a macro in
paper/AAMAS/tables/num_probes.tex is compared with that macro, and a mismatch raises.

Statistics: unit = game. Level CIs are 95% percentile bootstraps over the ten games of a
cell (offsets 6000+); shift CIs are exactly probes.shifts() (offsets 900+).
"""
